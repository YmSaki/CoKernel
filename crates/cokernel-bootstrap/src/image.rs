//! Build a first-boot-hardened validation image without extracting on the host.
use anyhow::{Context, Result, ensure};
use flate2::read::GzDecoder;
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::{
    collections::{BTreeMap, HashSet},
    fs::{File, OpenOptions},
    io::{Read, Seek, SeekFrom},
    path::Path,
};
use tar::{Archive, Builder, EntryType, Header};

pub const BASE_URL: &str = "https://cdimage.ubuntu.com/ubuntu-base/releases/24.04/release/ubuntu-base-24.04.5-base-amd64.tar.gz";
pub const BASE_SHA256: &str = "e77b6f10c2590cef872b33ee9f635a0e3fd1f57fb074c0e52b5c7f56147a0c86";
// Public Mozilla roots generated by Ubuntu ca-certificates 20260816ubuntu0.24.04.1.
pub const CA_SHA256: &str = "64e7c24b0536b525fb19b145768bd5e6e12ced0df3db837c34553ea789acd143";
const CA_BUNDLE: &str = "opt/cokernel/certs/ca-certificates.crt";
const SYSTEM_CA: &str = "etc/ssl/certs/ca-certificates.crt";
const PYTHON_CA: &str = "etc/ssl/cert.pem";
pub const CONTROL: u64 = 61001;
pub const WORKLOAD: u64 = 61002;
pub const POLICY: &str = "[boot]\nsystemd=false\ncommand=/opt/cokernel/bin/cokernel-bootstrap boot-guard\n[automount]\nenabled=false\nmountFsTab=false\n[interop]\nenabled=false\nappendWindowsPath=false\n[user]\ndefault=cokernel-control\n";
const MAX_ARCHIVE: u64 = 4 * 1024 * 1024 * 1024;
const REQUIRED: &[&str] = &[
    "opt/cokernel/bin/cokernel-runtime",
    "opt/cokernel/bin/cokernel-mcp",
    "opt/cokernel/bin/cokernel-bootstrap",
    "opt/cokernel/bin/uv",
    "opt/cokernel/bin/tunnel-client",
    "opt/cokernel/python/bin/python3.12",
    "opt/cokernel/worker/pyproject.toml",
    CA_BUNDLE,
];

#[derive(Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Manifest {
    pub schema: u8,
    pub identity: uuid::Uuid,
    pub base_sha256: String,
    pub payload_sha256: String,
    pub files: BTreeMap<String, String>,
}

pub fn hash_file(file: &mut File) -> Result<String> {
    ensure!(
        file.metadata()?.is_file() && file.metadata()?.len() <= MAX_ARCHIVE,
        "CK-SETUP-ARTIFACT: invalid artifact"
    );
    file.seek(SeekFrom::Start(0))?;
    let mut digest = Sha256::new();
    let mut bytes = [0; 65536];
    loop {
        let n = file.read(&mut bytes)?;
        if n == 0 {
            break;
        }
        digest.update(&bytes[..n]);
    }
    file.seek(SeekFrom::Start(0))?;
    Ok(format!("{:x}", digest.finalize()))
}

fn path_name(bytes: &[u8]) -> Result<String> {
    let text = std::str::from_utf8(bytes).context("CK-SETUP-PATH: non-UTF8 archive path")?;
    let text = text.trim_start_matches("./").trim_end_matches('/');
    ensure!(
        !text.starts_with('/') && !text.contains('\\') && !text.chars().any(char::is_control),
        "CK-SETUP-PATH: invalid archive path"
    );
    ensure!(
        text.split('/').all(|p| !matches!(p, ".." | "." | "")) || text.is_empty(),
        "CK-SETUP-PATH: invalid archive component"
    );
    Ok(text.into())
}

pub fn build(base: &Path, payload: &Path, output: &Path) -> Result<Manifest> {
    let mut base = File::open(base)?;
    ensure!(
        hash_file(&mut base)? == BASE_SHA256,
        "CK-SETUP-HASH: unexpected Ubuntu Base digest"
    );
    let mut payload = File::open(payload)?;
    let payload_sha256 = hash_file(&mut payload)?;
    let manifest = Manifest {
        schema: 1,
        identity: uuid::Uuid::new_v4(),
        base_sha256: BASE_SHA256.into(),
        payload_sha256,
        files: BTreeMap::new(),
    };
    let file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(output)?;
    // An interrupted/failed file is deliberately retained and cannot be reused
    // as a successfully built image without the separate completion manifest.
    let mut builder = Builder::new(file);
    let manifest = compose(
        &mut builder,
        GzDecoder::new(base),
        payload,
        manifest,
        CA_SHA256,
    )?;
    builder.finish()?;
    builder.into_inner()?.sync_all()?;
    Ok(manifest)
}

fn compose<W: std::io::Write, R: Read, P: Read>(
    builder: &mut Builder<W>,
    base: R,
    payload: P,
    mut manifest: Manifest,
    expected_ca: &str,
) -> Result<Manifest> {
    let mut accounts = BTreeMap::new();
    let mut total = 0u64;
    let mut names = HashSet::new();
    for entry in Archive::new(base).entries()? {
        let mut entry = entry?;
        let name = path_name(&entry.path_bytes())?;
        if name.is_empty() {
            continue;
        }
        total = total.checked_add(entry.size()).context("CK-SETUP-LIMIT")?;
        ensure!(
            total <= MAX_ARCHIVE && names.len() < 100_000 && names.insert(name.clone()),
            "CK-SETUP-LIMIT: duplicate or excessive base entries"
        );
        ensure!(
            !name.starts_with("opt/cokernel")
                && !name.starts_with("var/lib/cokernel")
                && !name.starts_with("etc/cokernel"),
            "CK-SETUP-COLLISION: product paths already present"
        );
        if matches!(name.as_str(), "etc/wsl.conf" | "etc/wsl-distribution.conf") {
            continue;
        }
        if matches!(name.as_str(), "etc/passwd" | "etc/group" | "etc/shadow") {
            ensure!(
                entry.header().entry_type().is_file() && entry.size() <= 65536,
                "CK-SETUP-ACCOUNTS: invalid base account file"
            );
            let mut text = String::new();
            entry.read_to_string(&mut text)?;
            accounts.insert(name, text);
            continue;
        }
        // Base is the exact pinned vendor archive. Preserve its usr-merge links
        // and device metadata; it is never extracted into a Windows directory.
        let mut header = entry.header().clone();
        if header.entry_type().is_symlink() || header.entry_type().is_hard_link() {
            let target = entry
                .link_name()?
                .context("CK-SETUP-PATH: missing vendor link")?
                .into_owned();
            builder.append_link(&mut header, &name, target)?;
        } else {
            builder.append_data(&mut header, &name, entry)?;
        }
    }
    for (name, extra) in [
        (
            "etc/passwd",
            "cokernel-control:x:61001:61001::/var/lib/cokernel/state:/bin/sh\ncokernel-workload:x:61002:61002::/var/lib/cokernel/projects:/usr/sbin/nologin\n",
        ),
        (
            "etc/group",
            "cokernel-control:x:61001:\ncokernel-workload:x:61002:cokernel-control\n",
        ),
        (
            "etc/shadow",
            "cokernel-control:!:20000:0:99999:7:::\ncokernel-workload:!:20000:0:99999:7:::\n",
        ),
    ] {
        let mut current = accounts
            .remove(name)
            .context("CK-SETUP-ACCOUNTS: missing base account file")?;
        ensure!(
            current.ends_with('\n')
                && !current.lines().any(|line| {
                    let fields: Vec<_> = line.split(':').collect();
                    fields.first().is_some_and(|v| v.starts_with("cokernel-"))
                        || (name != "etc/shadow"
                            && fields
                                .get(2)
                                .is_some_and(|v| matches!(*v, "61001" | "61002")))
                }),
            "CK-SETUP-ACCOUNTS: reserved account collision"
        );
        current.push_str(extra);
        append(
            builder,
            name,
            current.as_bytes(),
            if name == "etc/shadow" { 0o600 } else { 0o644 },
            0,
            0,
        )?;
    }
    append(builder, "etc/wsl.conf", POLICY.as_bytes(), 0o644, 0, 0)?;
    ensure!(
        !names.contains(SYSTEM_CA) && !names.contains(PYTHON_CA),
        "CK-SETUP-COLLISION: base contains CA bundle"
    );
    for path in ["etc/ssl", "etc/ssl/certs"] {
        if !names.contains(path) {
            directory(builder, path, 0, 0, 0o755)?;
        }
    }
    names.clear();
    for entry in Archive::new(payload).entries()? {
        let mut entry = entry?;
        let name = path_name(&entry.path_bytes())?;
        ensure!(
            name.starts_with("opt/cokernel/")
                && name != "opt/cokernel/launch"
                && names.insert(name.clone())
                && names.len() < 100_000,
            "CK-SETUP-PAYLOAD: invalid or duplicate payload path"
        );
        let kind = entry.header().entry_type();
        ensure!(
            kind.is_file() || kind.is_dir() || kind.is_symlink(),
            "CK-SETUP-PAYLOAD: unsupported entry kind"
        );
        total = total.checked_add(entry.size()).context("CK-SETUP-LIMIT")?;
        ensure!(
            total <= MAX_ARCHIVE,
            "CK-SETUP-LIMIT: expanded image too large"
        );
        if kind.is_symlink() {
            let target = entry
                .link_name_bytes()
                .context("CK-SETUP-PAYLOAD: missing link")?;
            let target = std::str::from_utf8(&target)?;
            ensure!(
                !target.is_empty()
                    && target.len() < 4096
                    && !target.starts_with('/')
                    && !target.contains('\\')
                    && !target.chars().any(char::is_control),
                "CK-SETUP-PAYLOAD: invalid link"
            );
            // No children may be placed beneath payload symlinks: checked after
            // enumeration, before publishing the completion manifest.
        }
        let mut header = entry.header().clone();
        header.set_uid(0);
        header.set_gid(0);
        // Extractors may prefer textual account names over numeric IDs.
        // Clear inherited root/root names before assigning the control GID.
        header.set_username("")?;
        header.set_groupname("")?;
        header.set_mode(if kind.is_dir() || header.mode()? & 0o111 != 0 {
            0o755
        } else {
            0o644
        });
        if name == REQUIRED[0] {
            ensure!(kind.is_file(), "CK-SETUP-PAYLOAD: Runtime must be regular");
            header.set_mode(0o750);
            header.set_gid(CONTROL);
        }
        header.set_cksum();
        if kind.is_file() {
            ensure!(
                entry.size() <= 512 * 1024 * 1024,
                "CK-SETUP-LIMIT: payload file too large"
            );
            let mut bytes = Vec::new();
            entry.read_to_end(&mut bytes)?;
            if name == CA_BUNDLE {
                ensure!(
                    bytes.len() <= 1024 * 1024
                        && format!("{:x}", Sha256::digest(&bytes)) == expected_ca,
                    "CK-SETUP-TRUST: unexpected CA bundle"
                );
                append(builder, SYSTEM_CA, &bytes, 0o644, 0, 0)?;
                append(builder, PYTHON_CA, &bytes, 0o644, 0, 0)?;
            }
            manifest
                .files
                .insert(name.clone(), format!("{:x}", Sha256::digest(&bytes)));
            builder.append_data(&mut header, &name, bytes.as_slice())?;
        } else if kind.is_symlink() {
            let target = String::from_utf8(
                entry
                    .link_name_bytes()
                    .context("CK-SETUP-PATH: missing payload link")?
                    .to_vec(),
            )?;
            manifest
                .files
                .insert(format!("link:{name}"), target.clone());
            builder.append_link(&mut header, &name, target)?;
        } else {
            builder.append_data(&mut header, &name, entry)?;
        }
    }
    for name in REQUIRED {
        ensure!(
            manifest.files.contains_key(*name),
            "CK-SETUP-PAYLOAD: missing required regular file"
        );
    }
    for key in manifest
        .files
        .keys()
        .filter_map(|key| key.strip_prefix("link:"))
    {
        ensure!(
            !names
                .iter()
                .any(|name| name.starts_with(&format!("{key}/"))),
            "CK-SETUP-PAYLOAD: content below symlink"
        );
    }
    validate_links(&names, &manifest.files)?;
    for (name, uid, gid, mode) in [
        ("opt/cokernel", 0, 0, 0o755),
        ("var/lib/cokernel", 0, 0, 0o755),
        ("var/lib/cokernel/state", CONTROL, CONTROL, 0o700),
        ("var/lib/cokernel/projects", CONTROL, WORKLOAD, 0o2770),
        ("var/lib/cokernel/sessions", CONTROL, WORKLOAD, 0o2710),
        ("var/cache/cokernel", 0, 0, 0o755),
        ("var/cache/cokernel/uv", WORKLOAD, WORKLOAD, 0o770),
        ("var/cache/cokernel/python", WORKLOAD, WORKLOAD, 0o770),
    ] {
        directory(builder, name, uid, gid, mode)?;
    }
    append(
        builder,
        "opt/cokernel/launch",
        include_bytes!("launch.sh"),
        0o750,
        0,
        CONTROL,
    )?;
    append(
        builder,
        "etc/cokernel-validation.json",
        &serde_json::to_vec(&manifest)?,
        0o644,
        0,
        0,
    )?;
    Ok(manifest)
}

fn append<W: std::io::Write>(
    builder: &mut Builder<W>,
    path: &str,
    bytes: &[u8],
    mode: u32,
    uid: u64,
    gid: u64,
) -> Result<()> {
    let mut h = Header::new_gnu();
    h.set_path(path)?;
    h.set_size(bytes.len() as u64);
    h.set_mode(mode);
    h.set_uid(uid);
    h.set_gid(gid);
    h.set_cksum();
    builder.append(&h, bytes)?;
    Ok(())
}
fn directory<W: std::io::Write>(
    builder: &mut Builder<W>,
    path: &str,
    uid: u64,
    gid: u64,
    mode: u32,
) -> Result<()> {
    let mut h = Header::new_gnu();
    h.set_path(path)?;
    h.set_entry_type(EntryType::Directory);
    h.set_size(0);
    h.set_uid(uid);
    h.set_gid(gid);
    h.set_mode(mode);
    h.set_cksum();
    builder.append(&h, std::io::empty())?;
    Ok(())
}

fn validate_links(names: &HashSet<String>, files: &BTreeMap<String, String>) -> Result<()> {
    use std::collections::VecDeque;
    let links: BTreeMap<_, _> = files
        .iter()
        .filter_map(|(k, v)| k.strip_prefix("link:").map(|k| (k, v.as_str())))
        .collect();
    for (&name, &target) in &links {
        let mut stack: Vec<&str> = name
            .rsplit_once('/')
            .context("CK-SETUP-PATH")?
            .0
            .split('/')
            .collect();
        let mut parts: VecDeque<&str> = target.split('/').collect();
        let mut expanded = 0;
        while let Some(part) = parts.pop_front() {
            match part {
                "" | "." => {}
                ".." => {
                    ensure!(
                        stack.len() > 2,
                        "CK-SETUP-PAYLOAD: link escapes product root"
                    );
                    stack.pop();
                }
                _ => {
                    stack.push(part);
                    if let Some(target) = links.get(stack.join("/").as_str()) {
                        expanded += 1;
                        ensure!(expanded <= 40, "CK-SETUP-PAYLOAD: cyclic link");
                        stack.pop();
                        for part in target.split('/').rev() {
                            parts.push_front(part);
                        }
                    }
                }
            }
        }
        ensure!(
            names.contains(&stack.join("/")),
            "CK-SETUP-PAYLOAD: dangling link"
        );
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    fn fixture(collision: bool, link_child: bool) -> (Vec<u8>, Vec<u8>, Manifest) {
        let mut base = Builder::new(Vec::new());
        for (name, value) in [
            ("etc/passwd", "root:x:0:0:root:/root:/bin/bash\n"),
            ("etc/group", "root:x:0:\n"),
            ("etc/shadow", "root:!:20000:0:99999:7:::\n"),
            ("etc/wsl.conf", "[automount]\nenabled=true\n"),
        ] {
            let text = if collision && name == "etc/group" {
                "other:x:61001:\n"
            } else {
                value
            };
            append(&mut base, name, text.as_bytes(), 0o644, 0, 0).unwrap();
        }
        let mut payload = Builder::new(Vec::new());
        for path in REQUIRED {
            let mut header = Header::new_gnu();
            header.set_size(7);
            header.set_mode(0o777);
            header.set_uid(999);
            header.set_gid(999);
            header.set_username("root").unwrap();
            header.set_groupname("root").unwrap();
            header.set_cksum();
            payload
                .append_data(&mut header, path, &b"payload"[..])
                .unwrap();
        }
        if link_child {
            let mut h = Header::new_gnu();
            h.set_entry_type(EntryType::Symlink);
            h.set_size(0);
            h.set_mode(0o777);
            payload
                .append_link(&mut h, "opt/cokernel/python/alias", "lib")
                .unwrap();
            append(
                &mut payload,
                "opt/cokernel/python/alias/injected",
                b"bad",
                0o644,
                0,
                0,
            )
            .unwrap();
        }
        let manifest = Manifest {
            schema: 1,
            identity: uuid::Uuid::new_v4(),
            base_sha256: BASE_SHA256.into(),
            payload_sha256: "a".repeat(64),
            files: BTreeMap::new(),
        };
        (
            base.into_inner().unwrap(),
            payload.into_inner().unwrap(),
            manifest,
        )
    }
    #[test]
    fn first_boot_policy_accounts_and_permissions_are_in_the_image() {
        let (base, payload, m) = fixture(false, false);
        let mut out = Builder::new(Vec::new());
        let result = compose(
            &mut out,
            base.as_slice(),
            payload.as_slice(),
            m,
            &format!("{:x}", Sha256::digest(b"payload")),
        )
        .unwrap();
        let bytes = out.into_inner().unwrap();
        let mut seen = HashSet::new();
        for e in Archive::new(bytes.as_slice()).entries().unwrap() {
            let mut e = e.unwrap();
            let name = path_name(&e.path_bytes()).unwrap();
            assert!(seen.insert(name.clone()));
            if name == "etc/wsl.conf" {
                let mut s = String::new();
                e.read_to_string(&mut s).unwrap();
                assert_eq!(s, POLICY);
            }
            if name == REQUIRED[0] {
                assert_eq!(e.header().gid().unwrap(), CONTROL);
                assert_eq!(e.header().username().unwrap().unwrap_or_default(), "");
                assert_eq!(e.header().groupname().unwrap().unwrap_or_default(), "");
                assert_eq!(e.header().mode().unwrap(), 0o750);
            }
            if name == "var/lib/cokernel/projects" {
                assert_eq!(e.header().gid().unwrap(), WORKLOAD);
                assert_eq!(e.header().mode().unwrap(), 0o2770);
            }
            if name == "etc/passwd" {
                let mut s = String::new();
                e.read_to_string(&mut s).unwrap();
                assert!(s.contains("cokernel-control:x:61001:61001:"));
            }
        }
        assert!(seen.contains("etc/cokernel-validation.json"));
        assert!(seen.contains(SYSTEM_CA));
        assert!(seen.contains(PYTHON_CA));
        assert_eq!(result.files.len(), REQUIRED.len());
    }
    #[test]
    fn collisions_and_payload_symlink_children_fail_before_completion() {
        for (collision, links) in [(true, false), (false, true)] {
            let (base, payload, m) = fixture(collision, links);
            let mut out = Builder::new(Vec::new());
            assert!(
                compose(
                    &mut out,
                    base.as_slice(),
                    payload.as_slice(),
                    m,
                    &format!("{:x}", Sha256::digest(b"payload"))
                )
                .is_err()
            );
        }
        for path in ["../escape", "/etc/passwd", "a/../b", "a//b", "a\\b", "a\n"] {
            assert!(path_name(path.as_bytes()).is_err(), "{path}");
        }
    }
    #[test]
    fn unpinned_trust_roots_cannot_produce_a_complete_image() {
        let (base, payload, m) = fixture(false, false);
        let mut out = Builder::new(Vec::new());
        let error =
            compose(&mut out, base.as_slice(), payload.as_slice(), m, CA_SHA256).unwrap_err();
        assert!(error.to_string().contains("CK-SETUP-TRUST"));
    }
    #[test]
    fn relative_link_resolution_stays_inside_payload_even_through_chains() {
        let names = HashSet::from([
            "opt/cokernel/python/a/value".into(),
            "opt/cokernel/python/b/alias".into(),
            "opt/cokernel/python/b/second".into(),
        ]);
        let mut files = BTreeMap::from([
            (
                "link:opt/cokernel/python/b/alias".into(),
                "../a/value".into(),
            ),
            ("link:opt/cokernel/python/b/second".into(), "alias".into()),
        ]);
        validate_links(&names, &files).unwrap();
        files.insert(
            "link:opt/cokernel/python/b/alias".into(),
            "../../../outside".into(),
        );
        assert!(validate_links(&names, &files).is_err());
        files.insert("link:opt/cokernel/python/b/alias".into(), "second".into());
        assert!(validate_links(&names, &files).is_err());
    }
}
